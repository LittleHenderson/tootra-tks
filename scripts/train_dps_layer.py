class SimpleDPSModel(nn.Module):
    """Simple fallback model if DPSGatingLayer unavailable."""

    def __init__(self, noetic_dim: int = 40, hidden_dim: int = 64):
        super().__init__()
        self.noetic_dim = noetic_dim

        # V/I/S computation networks
        self.validity_net = nn.Sequential(
            nn.Linear(noetic_dim, hidden_dim),
            nn.GELU(),
            nn.Linear(hidden_dim, 1),
            nn.Sigmoid(),
        )

        self.impact_net = nn.Sequential(
            nn.Linear(noetic_dim, hidden_dim),
            nn.GELU(),
            nn.Linear(hidden_dim, 1),
            nn.Sigmoid(),
        )

        self.similarity_net = nn.Sequential(
            nn.Linear(noetic_dim, hidden_dim),
            nn.GELU(),
            nn.Linear(hidden_dim, 1),
            nn.Sigmoid(),
        )

        # Classification head
        self.classifier = nn.Linear(noetic_dim + 3, 3)

        # Unlock prediction
        self.unlock_head = nn.Linear(noetic_dim + 3, 1)

        # State prediction
        self.state_head = nn.Linear(noetic_dim + 3, 3)  # p_max, tokens, cooldown

    def forward(self, x: torch.Tensor) -> Dict[str, torch.Tensor]:
        batch_size = x.shape[0]
        if x.dim() == 3:
            x = x.squeeze(1)  # [batch, dim]

        # Compute V, I, S
        v = self.validity_net(x).squeeze(-1)
        i = self.impact_net(x).squeeze(-1)
        s = self.similarity_net(x).squeeze(-1)

        # Compute NW = V x I x (1 - S)
        nw = v * i * (1 - s)

        # Features for classification
        features = torch.cat([x, v.unsqueeze(-1), i.unsqueeze(-1), s.unsqueeze(-1)], dim=-1)

        # Classification logits
        class_logits = self.classifier(features)

        # Unlock logit
        unlock_logit = self.unlock_head(features).squeeze(-1)

        # State prediction
        state_pred = self.state_head(features)

        return {
            'nw': nw,
            'novelty_weight': nw,
            'v': v,
            'i': i,
            's': s,
            'class_logits': class_logits,
            'unlock_logit': unlock_logit,
            'next_state': {
                'p_max': state_pred[:, 0] * 5,  # Scale to [0, 5]
                'tokens': state_pred[:, 1] * 5,  # Scale to [0, 5]
                'cooldown': state_pred[:, 2] * 10,  # Scale to [0, 10]
            },
        }


