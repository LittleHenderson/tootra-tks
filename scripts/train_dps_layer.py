class DPSDataset(Dataset):
    """Dataset for DPS layer training from consciousness unlock pack."""

    def __init__(
        self,
        data_path: str,
        noetic_dim: int = 40,
        max_samples: Optional[int] = None,
    ):
        self.noetic_dim = noetic_dim
        self.samples = []

        full_path = PROJECT_ROOT / data_path
        if full_path.exists():
            logger.info(f"Loading {full_path}")
            self._load_jsonl(full_path)

        if max_samples:
            self.samples = self.samples[:max_samples]

        logger.info(f"Loaded {len(self.samples)} DPS training samples")

    def _load_jsonl(self, path: Path) -> None:
        """Load samples from JSONL file."""
        with open(path, 'r', encoding='utf-8') as f:
            for line in f:
                try:
                    record = json.loads(line.strip())
                    sample = self._parse_record(record)
                    if sample is not None:
                        self.samples.append(sample)
                except json.JSONDecodeError:
                    continue

    def _parse_record(self, record: Dict) -> Optional[Dict]:
        """Parse a training record into a sample."""
        # NEW FORMAT: Synthetic data from generate_dps_training_data.py
        if 'context_features' in record:
            return self._parse_synthetic_record(record)

        # LEGACY FORMAT: Messages-based format
        messages = record.get('messages', [])

        # Find user and assistant messages
        user_msg = None
        assistant_msg = None
        for msg in messages:
            if msg.get('role') == 'user':
                user_msg = msg.get('content', '')
            elif msg.get('role') == 'assistant':
                assistant_msg = msg.get('content', '')

        if not user_msg or not assistant_msg:
            return None

        # Parse the structured output from assistant
        parsed = self._parse_assistant_output(assistant_msg)
        if parsed is None:
            return None

        # Parse user input for V, I, S components
        vis_components = self._parse_user_input(user_msg)

        return {
            'input_text': user_msg,
            'target_text': assistant_msg,
            **parsed,
            **vis_components,
        }

    def _parse_synthetic_record(self, record: Dict) -> Optional[Dict]:
        """
        Parse synthetic data from generate_dps_training_data.py.

        Expected fields:
        - context_features: List[float] - 40-dim embedding
        - validity, impact, similarity: float
        - novelty_weight: float
        - novelty_class: int (0=HEAVY, 1=COUNT, 2=NOCOUNT)
        - current_p_max, current_tokens, is_in_cooldown
        - should_unlock, next_p_max, next_tokens
        """
        try:
            return {
                # Context embedding (40-dim)
                'embedding': record['context_features'],

                # V, I, S components
                'v': record['validity'],
                'i': record['impact'],
                's': record['similarity'],

                # Target outputs
                'nw': record['novelty_weight'],
                'novelty_class': record['novelty_class'],
                'unlock': 1 if record['should_unlock'] else 0,

                # State info
                'prev_state': {
                    'p_max': record['current_p_max'],
                    'tokens': record['current_tokens'],
                    'cooldown': 10 if record['is_in_cooldown'] else 0,
                },
                'next_state': {
                    'p_max': record['next_p_max'],
                    'tokens': record['next_tokens'],
                    'cooldown': 10 if record['should_unlock'] else 0,
                },

                # Metadata
                'scenario_type': record.get('scenario_type', 'UNKNOWN'),
                'description': record.get('description', ''),
            }
        except KeyError as e:
            logger.warning(f"Missing field in synthetic record: {e}")
            return None

    def _parse_assistant_output(self, text: str) -> Optional[Dict]:
        """
        Parse structured assistant output.

        Expected format:
        NW/Class/Unlock/Reason: 0.XX/HEAVY|COUNT|NOCOUNT/YES|NO/...
        p_max/tokens/cooldown: X → Y / X → Y / X → Y
        """
        result = {}

        # Parse NW and classification
        nw_match = re.search(r'NW[^:]*:\s*([0-9.]+)\s*/\s*(HEAVY|COUNT|NOCOUNT)', text)
        if nw_match:
            result['nw'] = float(nw_match.group(1))
            result['novelty_class'] = NOVELTY_CLASS_MAP.get(nw_match.group(2), 2)
        else:
            return None

        # Parse unlock
        unlock_match = re.search(r'Unlock[^:]*:\s*(YES|NO)', text, re.IGNORECASE)
        if unlock_match:
            result['unlock'] = 1 if unlock_match.group(1).upper() == 'YES' else 0
        else:
            result['unlock'] = 0

        # Parse state transitions
        state_match = re.search(
            r'p_max[^:]*:\s*(\d+)\s*→\s*(\d+).*?'
            r'tokens[^:]*:\s*(\d+)\s*→\s*(\d+).*?'
            r'cooldown[^:]*:\s*(\d+)\s*→\s*(\d+)',
            text, re.IGNORECASE | re.DOTALL
        )
        if state_match:
            result['prev_state'] = {
                'p_max': int(state_match.group(1)),
                'tokens': int(state_match.group(3)),
                'cooldown': int(state_match.group(5)),
            }
            result['next_state'] = {
                'p_max': int(state_match.group(2)),
                'tokens': int(state_match.group(4)),
                'cooldown': int(state_match.group(6)),
            }
        else:
            # Default state
            result['prev_state'] = {'p_max': 2, 'tokens': 0, 'cooldown': 0}
            result['next_state'] = {'p_max': 2, 'tokens': 0, 'cooldown': 0}

        return result

    def _parse_user_input(self, text: str) -> Dict:
        """Parse V, I, S components from user input."""
        result = {}

        # Parse V (validity) - look for patterns like V=0.XX or validity=0.XX
        v_match = re.search(r'[Vv](?:alidity)?\s*[=:]\s*([0-9.]+)', text)
        if v_match:
            result['v'] = float(v_match.group(1))
        else:
            result['v'] = 0.5  # Default

        # Parse I (impact)
        i_match = re.search(r'[Ii](?:mpact)?\s*[=:]\s*([0-9.]+)', text)
        if i_match:
            result['i'] = float(i_match.group(1))
        else:
            result['i'] = 0.5  # Default

        # Parse S (similarity)
        s_match = re.search(r'[Ss](?:imilarity)?\s*[=:]\s*([0-9.]+)', text)
        if s_match:
            result['s'] = float(s_match.group(1))
        else:
            result['s'] = 0.5  # Default

        # Parse high-stakes mode
        result['high_stakes'] = 1 if 'high-stakes' in text.lower() or 'hs' in text.lower() else 0

        return result

    def __len__(self) -> int:
        return len(self.samples)

    def __getitem__(self, idx: int) -> Dict:
        sample = self.samples[idx]

        # Use pre-computed embedding if available (synthetic data)
        if 'embedding' in sample:
            noetic_input = torch.tensor(sample['embedding'], dtype=torch.float32)
        else:
            # Fallback: Generate pseudo-random embeddings from text hash
            text_hash = hash(sample.get('input_text', str(idx))) % (2**32)
            torch.manual_seed(text_hash)
            noetic_input = torch.randn(self.noetic_dim)

        # Handle optional high_stakes field
        high_stakes = sample.get('high_stakes', 0)

        return {
            'noetic_input': noetic_input,
            'nw': torch.tensor(sample['nw'], dtype=torch.float32),
            'v': torch.tensor(sample['v'], dtype=torch.float32),
            'i': torch.tensor(sample['i'], dtype=torch.float32),
            's': torch.tensor(sample['s'], dtype=torch.float32),
            'novelty_class': torch.tensor(sample['novelty_class']),
            'unlock': torch.tensor(sample['unlock']),
            'prev_p_max': torch.tensor(sample['prev_state']['p_max'], dtype=torch.float32),
            'prev_tokens': torch.tensor(sample['prev_state']['tokens'], dtype=torch.float32),
            'prev_cooldown': torch.tensor(sample['prev_state']['cooldown'], dtype=torch.float32),
            'next_p_max': torch.tensor(sample['next_state']['p_max'], dtype=torch.float32),
            'next_tokens': torch.tensor(sample['next_state']['tokens'], dtype=torch.float32),
            'next_cooldown': torch.tensor(sample['next_state']['cooldown'], dtype=torch.float32),
            'high_stakes': torch.tensor(high_stakes),
        }


def collate_fn(batch: List[Dict]) -> Dict:
    """Collate batch of samples."""
    return {
        'noetic_input': torch.stack([s['noetic_input'] for s in batch]),
        'nw': torch.stack([s['nw'] for s in batch]),
        'v': torch.stack([s['v'] for s in batch]),
        'i': torch.stack([s['i'] for s in batch]),
        's': torch.stack([s['s'] for s in batch]),
        'novelty_class': torch.stack([s['novelty_class'] for s in batch]),
        'unlock': torch.stack([s['unlock'] for s in batch]),
        'prev_state': {
            'p_max': torch.stack([s['prev_p_max'] for s in batch]),
            'tokens': torch.stack([s['prev_tokens'] for s in batch]),
            'cooldown': torch.stack([s['prev_cooldown'] for s in batch]),
        },
        'next_state': {
            'p_max': torch.stack([s['next_p_max'] for s in batch]),
            'tokens': torch.stack([s['next_tokens'] for s in batch]),
            'cooldown': torch.stack([s['next_cooldown'] for s in batch]),
        },
        'high_stakes': torch.stack([s['high_stakes'] for s in batch]),
    }


