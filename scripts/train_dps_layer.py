def train_dps_layer(config: DPSTrainingConfig) -> None:
    """Main training loop for DPS layer."""

    # Setup device - GPU ONLY (no CPU training allowed)
    device = enforce_gpu()
    logger.info(f"Using device: {device}")

    # Create output directory
    checkpoint_dir = Path(config.checkpoint_dir)
    checkpoint_dir.mkdir(parents=True, exist_ok=True)

    # Load dataset
    dataset = DPSDataset(config.data_path, noetic_dim=config.noetic_dim)

    # Split train/val
    train_size = int(len(dataset) * config.train_split)
    val_size = len(dataset) - train_size
    train_dataset, val_dataset = torch.utils.data.random_split(
        dataset, [train_size, val_size]
    )

    train_loader = DataLoader(
        train_dataset,
        batch_size=config.batch_size,
        shuffle=True,
        collate_fn=collate_fn,
        num_workers=0,
    )
    val_loader = DataLoader(
        val_dataset,
        batch_size=config.batch_size,
        shuffle=False,
        collate_fn=collate_fn,
        num_workers=0,
    )

    logger.info(f"Train samples: {len(train_dataset)}, Val samples: {len(val_dataset)}")

    # Load model
    try:
        from tks_features.dps_gating import DPSGatingLayer, DPSConfig
        dps_config = DPSConfig(
            hidden_dim=config.hidden_dim,
            validity_dim=config.validity_dim,
            impact_dim=config.impact_dim,
            heavy_threshold=config.heavy_threshold,
            count_threshold=config.count_threshold,
            n_tokens_threshold=config.n_tokens_threshold,
            cooldown_k=config.cooldown_k,
            max_depth=config.max_depth,
        )
        model = DPSGatingLayer(dps_config, noetic_dim=config.noetic_dim)
    except ImportError:
        logger.warning("DPSGatingLayer not found, using simple model")
        model = SimpleDPSModel(config.noetic_dim, config.hidden_dim)

    model = model.to(device)
    logger.info(f"Model parameters: {sum(p.numel() for p in model.parameters()):,}")

    # Optimizer and scheduler
    optimizer = AdamW(
        model.parameters(),
        lr=config.learning_rate,
        weight_decay=config.weight_decay,
    )
    scheduler = CosineAnnealingLR(
        optimizer,
        T_max=len(train_loader) * config.epochs,
    )

    # Loss functions
    loss_config = STRGLossConfig(
        lambda_novelty_weight=config.lambda_novelty,
        lambda_classification=config.lambda_classification,
        lambda_state_update=config.lambda_state,
    )
    dps_loss_fn = DPSTrainingLoss(
        config=loss_config,
        heavy_threshold=config.heavy_threshold,
        count_threshold=config.count_threshold,
    )

    # Training loop
    global_step = 0
    best_val_loss = float('inf')

    for epoch in range(config.epochs):
        model.train()
        epoch_loss = 0.0
        epoch_steps = 0
        epoch_accuracy = 0.0

        for batch_idx, batch in enumerate(train_loader):
            # Move to device
            noetic_input = batch['noetic_input'].to(device)
            target_nw = batch['nw'].to(device)
            target_v = batch['v'].to(device)
            target_i = batch['i'].to(device)
            target_s = batch['s'].to(device)
            target_class = batch['novelty_class'].to(device)
            target_unlock = batch['unlock'].to(device)
            next_state = {k: v.to(device) for k, v in batch['next_state'].items()}

            # Forward pass
            optimizer.zero_grad()

            if hasattr(model, 'compute_novelty_batch'):
                # DPSGatingLayer with batch-compatible training method
                output = model.compute_novelty_batch(noetic_input.unsqueeze(1))

                predictions = {
                    'novelty': {
                        'nw': output['nw'],
                        'v': output['v'],
                        'i': output['i'],
                        's': output['s'],
                    },
                    'class_logits': output['class_logits'],
                    'unlock_logit': torch.zeros_like(target_unlock.float()),
                    'next_state': next_state,
                }
            elif hasattr(model, 'compute_novelty'):
                # Legacy DPSGatingLayer path (scalar output - will fail with batch loss)
                novelty = model.compute_novelty(noetic_input.unsqueeze(1))

                predictions = {
                    'novelty': {
                        'nw': torch.tensor([novelty.value] * len(target_nw), device=device),
                        'v': torch.tensor([novelty.validity.value] * len(target_nw), device=device),
                        'i': torch.tensor([novelty.impact.value] * len(target_nw), device=device),
                        's': torch.tensor([novelty.similarity.value] * len(target_nw), device=device),
                    },
                    'class_logits': torch.zeros(len(target_nw), 3, device=device),
                    'unlock_logit': torch.zeros_like(target_unlock.float()),
                    'next_state': next_state,
                }
            elif hasattr(model, 'forward_training'):
                output = model.forward_training(noetic_input.unsqueeze(1))
                predictions = {
                    'novelty': {
                        'nw': output.get('nw', output.get('novelty_weight', torch.zeros_like(target_nw))),
                        'v': output.get('v', torch.zeros_like(target_v)),
                        'i': output.get('i', torch.zeros_like(target_i)),
                        's': output.get('s', torch.zeros_like(target_s)),
                    },
                    'class_logits': output.get('class_logits', torch.zeros(len(target_nw), 3, device=device)),
                    'next_state': output.get('next_state', next_state),
                    'unlock_logit': output.get('unlock_logit', torch.zeros_like(target_unlock.float())),
                }
            else:
                output = model(noetic_input.unsqueeze(1))
                predictions = {
                    'novelty': {
                        'nw': output.get('nw', output.get('novelty_weight', torch.zeros_like(target_nw))),
                        'v': output.get('v', torch.zeros_like(target_v)),
                        'i': output.get('i', torch.zeros_like(target_i)),
                        's': output.get('s', torch.zeros_like(target_s)),
                    },
                    'class_logits': output.get('class_logits', torch.zeros(len(target_nw), 3, device=device)),
                    'next_state': output.get('next_state', next_state),
                    'unlock_logit': output.get('unlock_logit', torch.zeros_like(target_unlock.float())),
                }

            # Prepare targets dict
            targets = {
                'nw': target_nw,
                'v': target_v,
                'i': target_i,
                's': target_s,
                'novelty_class': target_class,
                'unlock': target_unlock,
                'next_state': next_state,
            }

            # Compute loss
            loss_dict = dps_loss_fn(predictions, targets)
            total_loss = loss_dict['total']

            # Backward pass
            total_loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), config.max_grad_norm)
            optimizer.step()
            scheduler.step()

            epoch_loss += total_loss.item()
            epoch_steps += 1
            global_step += 1

            if 'classification_accuracy' in loss_dict:
                epoch_accuracy += loss_dict['classification_accuracy'].item()

            # Logging
            if global_step % config.log_every == 0:
                avg_loss = epoch_loss / epoch_steps
                avg_acc = epoch_accuracy / epoch_steps
                lr = scheduler.get_last_lr()[0]
                logger.info(
                    f"Step {global_step} | Epoch {epoch+1}/{config.epochs} | "
                    f"Loss: {avg_loss:.4f} | Acc: {avg_acc:.4f} | LR: {lr:.2e}"
                )

            # Checkpointing
            if global_step % config.save_every == 0:
                save_checkpoint(
                    model, optimizer, scheduler, global_step, epoch,
                    checkpoint_dir / f"step_{global_step}.pt"
                )

        # End of epoch
        avg_epoch_loss = epoch_loss / max(epoch_steps, 1)
        avg_epoch_acc = epoch_accuracy / max(epoch_steps, 1)
        logger.info(f"Epoch {epoch+1} complete. Avg loss: {avg_epoch_loss:.4f}, Avg acc: {avg_epoch_acc:.4f}")

        # Validation
        val_loss, val_acc = validate(model, val_loader, device, dps_loss_fn)
        logger.info(f"Validation loss: {val_loss:.4f}, acc: {val_acc:.4f}")

        if val_loss < best_val_loss:
            best_val_loss = val_loss
            save_checkpoint(
                model, optimizer, scheduler, global_step, epoch,
                checkpoint_dir / "best.pt"
            )
            logger.info(f"New best model saved (val_loss: {val_loss:.4f})")

    # Save final model
    save_checkpoint(
        model, optimizer, scheduler, global_step, epoch,
        checkpoint_dir / "final.pt"
    )
    logger.info("Training complete!")

    # Export pretrained weights
    torch.save(model.state_dict(), checkpoint_dir / "dps_layer_pretrained.pt")
    logger.info(f"Exported pretrained weights to {checkpoint_dir / 'dps_layer_pretrained.pt'}")


